"""Writes the Downloads table of docs/data-sources.md from sources.lock.json."""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
DOC = HERE.parents[1] / "docs" / "data-sources.md"
MARK = "<!-- generated by scripts/data/docs.py from scripts/data/sources.lock.json -->"

lock = json.loads((HERE / "sources.lock.json").read_text())
rows = ["| File | Retrieved | Bytes | SHA-256 |", "| --- | --- | --- | --- |"]
for key, e in sorted(lock.items()):
    name = f"[{key}]({e['url']})" if e["url"].startswith("https://") and " " not in e["url"] else f"{key} (Wikidata Query Service)"
    rows.append(f"| {name} | {e['retrieved']} | {e['bytes']} | `{e['sha256']}` |")
text = DOC.read_text(encoding="utf-8")
head = text.split(MARK)[0]
DOC.write_text(head + MARK + "\n\n" + "\n".join(rows) + "\n", encoding="utf-8")
